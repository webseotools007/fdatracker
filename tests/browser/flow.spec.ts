import { test,expect } from "@playwright/test";
test("landing, review approval, User isolation, search and responsive layouts",async({page,request})=>{
 await page.goto("/");
 await expect(page.getByRole("heading",{name:/FDA intelligence/})).toBeVisible();
 await page.getByRole("button",{name:"Log in",exact:true}).click();
 await page.getByRole("button",{name:/^Log in as Admin/}).click();
 await expect(page.getByRole("heading",{name:/Your daily perspective/})).toBeVisible();
 await page.getByRole("button",{name:/Review queue/}).click();
 await expect(page.getByRole("heading",{name:"Ready for your review."})).toBeVisible();
 const first=page.locator(".record-title").first();
 const title=await first.textContent();expect(title).toBeTruthy();
 await first.click();
 await page.getByRole("textbox",{name:"Review rationale"}).fill("Browser test approval for isolated fixture database");
 await page.getByRole("button",{name:"Approve & publish",exact:true}).click();
 await expect(page.getByRole("status").filter({hasText:"Publication approved"})).toBeVisible();
 await page.getByRole("button",{name:"Switch experience"}).click();
 await page.getByRole("button",{name:"Log in",exact:true}).click();
 await page.getByRole("button",{name:/^Log in as User/}).click();
 await expect(page.getByRole("button",{name:title!,exact:true})).toBeVisible();
 expect(await page.locator(".record-title").first().evaluate(el=>parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThanOrEqual(16);
 await expect(page.getByRole("heading",{name:"Regulatory activity",exact:true})).toBeVisible();
 await expect(page.getByRole("heading",{name:"Your signal mix",exact:true})).toBeVisible();
 await expect(page.locator(".month-column")).toHaveCount(6);
 await page.getByRole("combobox",{name:"Chart period"}).selectOption("3");
 await expect(page.locator(".month-column")).toHaveCount(3);
 const analytics=await (await page.request.get("/api/analytics?months=3")).json();
 const approved=await (await page.request.get("/api/records")).json();
 expect(analytics.scope).toBe("approved");
 expect(analytics.total).toBeLessThanOrEqual(approved.total);
 await page.locator(".month-column").last().click();
 await expect(page.getByRole("combobox",{name:"Date range"})).toHaveValue("chart");
 await expect(page.locator(".skeleton-list")).toHaveCount(0);
 const filterValue=await page.getByRole("combobox",{name:"Date range"}).inputValue();
 expect(filterValue).toBe("chart");
 await page.getByRole("combobox",{name:"Date range"}).selectOption("all");
 await expect(page.getByRole("button",{name:title!,exact:true})).toBeVisible();
 await expect(page.getByRole("button",{name:/Review queue/})).toHaveCount(0);
 expect((await page.request.get("/api/sources")).status()).toBe(403);
 expect((await page.request.patch("/api/records",{data:{}})).status()).toBe(403);
 const data=await (await page.request.get("/api/records?status=all")).json();
 expect(data.items.every((x:{status:string})=>x.status==="approved")).toBeTruthy();
 await page.getByRole("textbox",{name:"Search publications"}).fill("NoSuchCompany987654");
 await page.getByRole("button",{name:"Search",exact:true}).click();
 await expect(page.getByRole("heading",{name:"No publications here yet."})).toBeVisible();
 await page.getByRole("button",{name:"Clear filters"}).click();
 await page.setViewportSize({width:390,height:844});
 expect(await page.locator(".record-title").first().evaluate(el=>parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThanOrEqual(16);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.getByRole("button",{name:"Toggle navigation"}).click();
 await expect(page.getByRole("button",{name:/Public Form 483s/}).first()).toBeVisible();
 await page.getByRole("button",{name:"Toggle navigation"}).click();
 await page.goto("/");expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.setViewportSize({width:1440,height:1000});
 expect(await page.locator("body").evaluate(el=>getComputedStyle(el).fontFamily)).toContain("Manrope");
 expect(await page.locator(".hero-copy > p").evaluate(el=>parseFloat(getComputedStyle(el).fontSize))).toBeGreaterThanOrEqual(16);
 expect((await request.get("/api/records")).status()).toBe(401);
 expect((await request.get("/api/analytics")).status()).toBe(401);
});
