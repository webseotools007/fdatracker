import { test,expect } from "@playwright/test";
test("production homepage opens manager preview without enabling server demo login",async({page})=>{
 test.skip(process.env.TEST_PRODUCTION!=="true","Production-only entry flow");
 await page.goto("/");
 await page.getByRole("button",{name:"Log in",exact:true}).click();
 await expect(page.getByRole("dialog")).toContainText("manager preview");
 await page.getByRole("button",{name:/^Log in as User/}).click();
 await expect(page).toHaveURL(/\/preview\?role=user/);
 await expect(page.getByRole("heading",{name:"Regulatory activity",exact:true})).toBeVisible();
 expect((await page.request.post("/api/session",{data:{role:"admin"}})).status()).toBe(403);
 await page.getByRole("button",{name:"Switch experience"}).click();
 await page.getByRole("button",{name:"Log in",exact:true}).click();
 await page.getByRole("button",{name:/^Log in as Admin/}).click();
 await expect(page).toHaveURL(/\/preview\?role=admin/);
 await expect(page.getByRole("navigation",{name:"Admin navigation"})).toBeVisible();
});
test("hosted manager preview has charts, tab-only reviews and no live writes",async({page})=>{
 await page.goto("/preview?role=admin");
 await expect(page.getByRole("heading",{name:"Regulatory activity",exact:true})).toBeVisible();
 await expect(page.locator(".local-label")).toHaveText("Manager preview");
 await expect(page.locator(".demo-notice")).toContainText("no live sync or real account access");
 await page.getByRole("button",{name:/Review queue/}).click();
 await expect(page.locator(".record-title").first()).toBeVisible();
 const title=(await page.locator(".record-title").first().textContent())!;
 await page.locator(".record-title").first().click();
 await page.getByRole("textbox",{name:"Review rationale"}).fill("Manager preview approval");
 await page.getByRole("button",{name:"Approve & publish",exact:true}).click();
 await expect(page.getByRole("status")).toContainText("this browser tab only");
 await page.reload();
 await page.getByRole("button",{name:/Data connections/}).click();
 await expect(page.getByRole("button",{name:"Live sync not connected"})).toHaveCount(4);
 for(const button of await page.getByRole("button",{name:"Live sync not connected"}).all())await expect(button).toBeDisabled();
 await page.goto("/preview?role=user");
 await page.getByRole("textbox",{name:"Search publications"}).fill(title);
 await page.getByRole("button",{name:"Search",exact:true}).click();
 await expect(page.getByRole("button",{name:title,exact:true}).first()).toBeVisible();
 await expect(page.getByRole("navigation",{name:"Admin navigation"})).toHaveCount(0);
 expect((await page.request.patch("/api/records",{data:{}})).status()).toBe(403);
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth)).toBe(true);
});
